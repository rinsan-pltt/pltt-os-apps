    mime: Optional[str] = None
    if body.selected_image_url:
        try:
            image_b64, mime = await _fetch_image_b64(body.selected_image_url)
        except Exception as e:  # noqa: BLE001 — fall back to text-only
            logger.warning("story chat: could not fetch selected image: %s", e)


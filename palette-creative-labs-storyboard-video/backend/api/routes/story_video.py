# User-selectable LLM for the writing steps (plan, motion prompts, chat) — maps
# the frontend's `llm` value to (secret name, model id, text call, vision
# call). "Latest" per model family as of this build: Opus 4.8, Sonnet 5,
# Haiku 4.5. Placed after the vision helpers above since the dict literal
# references them by name at import time.
_LLM_PROVIDERS: dict[str, tuple[str, str, Any, Any]] = {
    "claude_opus": ("ANTHROPIC_API_KEY", "claude-opus-4-8", _anthropic_json, _anthropic_vision_json),
    "claude_sonnet": ("ANTHROPIC_API_KEY", "claude-sonnet-5", _anthropic_json, _anthropic_vision_json),
    "claude_haiku": ("ANTHROPIC_API_KEY", "claude-haiku-4-5-20251001", _anthropic_json, _anthropic_vision_json),
    "gpt": ("OPENAI_KEY", "gpt-5.5", _openai_json, _openai_vision_json),
    "gemini": ("GOOGLE_AI_API_KEY", "gemini-3.1-pro", _gemini_json, _gemini_vision_json),
}
_DEFAULT_LLM = "gpt"


async def _llm_json(
    ctx: PluginContext,
    system: str,
    user: str,
    llm: Optional[str] = None,
    image_b64: Optional[str] = None,
    mime: Optional[str] = None,
) -> dict:
    """Text (or, with `image_b64`, vision) JSON call to the user-selected LLM,
    falling back through every other configured provider on failure."""
    llm = (llm or "").strip().lower()
    order = [llm] if llm in _LLM_PROVIDERS else []
    order += [p for p in _LLM_PROVIDERS if p not in order]  # try the rest as a fallback

    errors: list[str] = []
    for provider in order:
        secret_name, model, call, vision_call = _LLM_PROVIDERS[provider]
        api_key = read_secret(ctx, secret_name)
        if not api_key:
            continue
        try:
            if image_b64:
                return await vision_call(api_key, system, user, image_b64, mime or "image/png", model)
            return await call(api_key, system, user, model)
        except Exception as e:  # noqa: BLE001 — fall through to the next provider
            errors.append(f"{provider}: {e}")
            logger.warning("story LLM via %s failed: %s", provider, e)
    raise HTTPException(
        status_code=502,
        detail="; ".join(errors)
        or "No LLM configured (set ANTHROPIC_API_KEY, OPENAI_KEY, or GOOGLE_AI_API_KEY)",
    )



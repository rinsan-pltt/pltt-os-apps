async def _fetch_image_b64(url: str) -> tuple[str, str]:
    """Returns (base64_data, mime_type) for an image URL. Handles the local
    dev-storage file:// URLs the asset uploader hands out, plus data: URIs."""
    m = re.match(r"^data:(?P<type>[\w/+.-]+);base64,(?P<b64>.+)$", url, re.DOTALL)
    if m:
        return m.group("b64"), m.group("type")
    if url.startswith("file://"):
        path = Path(unquote(urlparse(url).path))
        data = path.read_bytes()
        mime = mimetypes.guess_type(path.name)[0] or "image/png"
        return base64.b64encode(data).decode("ascii"), mime
    async with httpx.AsyncClient(timeout=60, follow_redirects=True) as client:
        resp = await client.get(url)
        resp.raise_for_status()
        mime = (resp.headers.get("content-type") or "image/png").split(";")[0].strip()
        return base64.b64encode(resp.content).decode("ascii"), mime



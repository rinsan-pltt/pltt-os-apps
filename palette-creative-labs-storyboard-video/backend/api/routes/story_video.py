@router.post("/story/reference/analyze", dependencies=[require_permission("resources:write")])
async def analyze_story_reference(
    body: ReferenceAnalyzeRequest,
    ctx: PluginContext = Depends(get_ctx),
):
    """Analyses a reference image with a vision model (Gemini primary — the
    user-facing contract — OpenAI fallback) and persists {kind, name,
    description} on the asset row so the analysis rides content-hash dedup."""
    url = (body.url or "").strip()
    if not url:
        raise HTTPException(status_code=400, detail="url is required")

    # Already analysed (same asset re-used or re-uploaded) → reuse. Without an
    # asset_id, fall back to the URL — e.g. a video-mode start frame surfacing
    # in the Long Video references only knows its hosted URL.
    asset = None
    if body.asset_id:
        asset = await get_asset(ctx.db, ctx.user_id, body.asset_id)
    if asset is None:
        asset = await get_asset_by_url(ctx.db, ctx.user_id, url)
    if asset and isinstance(asset.get("analysis"), dict) and asset["analysis"].get("description"):
        return {"status": "cached", "analysis": asset["analysis"]}

    try:
        image_b64, mime = await _fetch_image_b64(url)
    except Exception as e:  # noqa: BLE001 — bad/unreachable reference URL
        raise HTTPException(status_code=400, detail=f"Could not fetch reference image: {e}")

    prompt = "Analyse this reference image for the film."
    errors: list[str] = []
    analysis: Optional[dict] = None
    gemini_key = read_secret(ctx, "GOOGLE_AI_API_KEY")
    if gemini_key:
        try:
            analysis = _clean_analysis(
                await _gemini_vision_json(gemini_key, _ANALYZE_SYSTEM, prompt, image_b64, mime)
            )
        except Exception as e:  # noqa: BLE001 — fall through to OpenAI
            errors.append(f"gemini: {e}")
            logger.warning("reference analysis via Gemini failed: %s", e)
    if analysis is None:
        openai_key = read_secret(ctx, "OPENAI_KEY")
        if openai_key:
            try:
                analysis = _clean_analysis(
                    await _openai_vision_json(openai_key, _ANALYZE_SYSTEM, prompt, image_b64, mime)
                )
            except Exception as e:  # noqa: BLE001
                errors.append(f"openai: {e}")
                logger.warning("reference analysis via OpenAI failed: %s", e)
    if analysis is None:
        raise HTTPException(
            status_code=502,
            detail="; ".join(errors)
            or "No vision LLM configured (set GOOGLE_AI_API_KEY or OPENAI_KEY)",
        )

    # Persist on the matched asset (by id or URL) so re-analyses stay cached.
    if asset:
        await set_asset_analysis(ctx.db, ctx.user_id, asset["id"], analysis)

    return {"status": "success", "analysis": analysis}



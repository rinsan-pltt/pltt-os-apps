_AUDIO_CAPABLE_VIDEO_MODELS = {"kling_3_0_pro", "kling_3_0_standard", "kling_o3_pro", "seedance_2_0"}

_VIDEO_PROMPT_AUDIO_GENERATED_RULE = """
- AUDIO: this clip renders audio generated by the model directly from this prompt's wording — describe what should be HEARD as part of the scene (ambient sound, foley, distinct sound effects, brief dialogue/vocalizations if a character speaks, mood-appropriate score or music cues), woven into the same sentence(s) describing the visual action rather than listed separately."""

_VIDEO_PROMPT_AUDIO_SILENT_RULE = """
- AUDIO: this clip renders with NO audio track — do not describe any sound, dialogue, music or sound effect; keep the prompt purely visual."""


class ScenePromptIn(BaseModel):
    index: int
    title: Optional[str] = ""
    duration: int
    image_prompt: str


class VideoPromptsRequest(BaseModel):
    prompt: Optional[str] = ""
    story: str
    # "bridge" (start→next-start keyframe bridging), "cinematic" (multi-angle
    # shot list within each clip, still bridged when the model supports it),
    # or "independent" (plain single-motion clips).
    continuity: Optional[str] = None
    # The video model the scenes will be generated with — picks the cinematic
    # prompt format (Kling's native pipe multi-prompt vs. a generic
    # timestamped shot list for everyone else).
    video_model: Optional[str] = None
    # "generated" (model-native ambience/sound/dialogue) or "silent" — decides
    # whether motion prompts describe audio cues at all, since audio-capable
    # models generate sound FROM the same prompt text driving the visuals.
    audio: Optional[str] = None
    # The plan's locked production design; motion prompts must respect it.
    bible: Optional[Dict[str, Any]] = None
    scenes: List[ScenePromptIn]
    # User-picked writer LLM: "claude_opus" | "claude_sonnet" | "gpt" | "gemini".
    llm: Optional[str] = None


@router.post("/story/video-prompts", dependencies=[require_permission("resources:write")])
async def story_video_prompts(
    body: VideoPromptsRequest,
    ctx: PluginContext = Depends(get_ctx),
):
    if not body.scenes:
        raise HTTPException(status_code=400, detail="scenes are required")
    continuity = (body.continuity or "").strip()
    video_model = (body.video_model or "").strip()
    # Cinematic clips are ALSO bridged (start+end frame) whenever the model
    # supports it — multi-angle choreography and seamless cuts are additive,
    # not alternatives.
    will_bridge = continuity in ("bridge", "cinematic") and _supports_end_frame(video_model)
    system = _VIDEO_PROMPT_SYSTEM
    if will_bridge:
        system += _VIDEO_PROMPT_BRIDGE_RULE
    if continuity == "cinematic":
        system += (
            _VIDEO_PROMPT_CINEMATIC_KLING_RULE
            if video_model.startswith("kling")
            else _VIDEO_PROMPT_CINEMATIC_GENERIC_RULE
        )
    # Only tell the model to WRITE audio cues when this video model can
    # actually RENDER audio from them — otherwise the instruction would just
    # add inert text (see _AUDIO_CAPABLE_VIDEO_MODELS).
    audio = (body.audio or "generated").strip().lower()
    if audio == "silent":
        system += _VIDEO_PROMPT_AUDIO_SILENT_RULE
    elif video_model in _AUDIO_CAPABLE_VIDEO_MODELS:
        system += _VIDEO_PROMPT_AUDIO_GENERATED_RULE
    bible = _normalize_bible(body.bible)
    if bible:
        system += (
            "\n- Respect the LOCKED production design below in every shot — the lens, "
            "camera height, movement style, lighting and grade never change between "
            "shots unless a scene explicitly demands it."
        )
    lines = [
        f"Scene {s.index} — \"{s.title or ''}\" ({s.duration}s): {s.image_prompt}"
        for s in body.scenes
    ]
    user = (
        (f"Original idea:\n{body.prompt}\n\n" if (body.prompt or "").strip() else "")
        + f"Story:\n{body.story}\n\n"
        + (
            "Locked production design:\n"
            + "\n".join(f"- {k}: {v}" for k, v in bible.items())
            + "\n\n"
            if bible
            else ""
        )
        + "Scenes:\n" + "\n".join(lines)
    )
    data = await _llm_json(ctx, system, user, body.llm)
    by_index: dict[int, str] = {}
    for s in data.get("scenes") or []:
        if not isinstance(s, dict):
            continue
        vp = str(s.get("video_prompt") or "").strip()
        try:
            idx = int(s.get("index"))
        except (TypeError, ValueError):
            continue
        if vp:
            by_index[idx] = vp
    return {
        "status": "success",
        "scenes": [
            {
                "index": s.index,
                # Fall back to animating the image prompt when the LLM skipped one.
                "video_prompt": by_index.get(s.index)
                or f"{s.image_prompt} — cinematic camera movement, natural motion",
            }
            for s in body.scenes
        ],
    }



def _local_media_dir() -> Path:
    # backend/api/routes/story_video.py → plugin root is three levels up.
    return Path(__file__).resolve().parents[3] / ".palette" / "story-media"


_MEDIA_CONTENT_TYPES = {
    "mp4": "video/mp4",
    "jpg": "image/jpeg",
    "jpeg": "image/jpeg",
    "png": "image/png",
    "webp": "image/webp",
}


async def _store_media(ctx: PluginContext, data: bytes, content_type: str, ext: str) -> str:
    """Upload media bytes to app storage. Local dev storage hands back
    file:// URLs that browsers refuse — there the bytes are kept in a local
    cache served by GET /story/media/{name} instead. Shared by the merged
    video AND the scene-media endpoint (image/video uploads, thumbnails)."""
    ext = ext.lstrip(".").lower() or "mp4"
    key = f"story_board_video/outputs/videos/{uuid.uuid4()}.{ext}"
    name = key.rsplit("/", 1)[-1]
    saved = await ctx.storage.upload_file(name, data, content_type, key=key)
    url = saved.get("file_url") or saved.get("fileUrl") or saved.get("url")
    if isinstance(url, str) and not url.startswith("file://"):
        return url
    cache = _local_media_dir()
    cache.mkdir(parents=True, exist_ok=True)
    (cache / name).write_bytes(data)
    logger.info("📁 Local dev storage: serving %s via /story/media/%s", content_type, name)
    return f"{_PLUGIN_BASE}/story/media/{name}"


async def _store_merged(ctx: PluginContext, data: bytes) -> str:
    return await _store_media(ctx, data, "video/mp4", "mp4")


_MEDIA_NAME_RE = re.compile(r"^[a-f0-9-]{36}\.(mp4|jpg|jpeg|png|webp)$")


@router.get("/story/media/{name}", dependencies=[require_permission("resources:read")])
async def story_media(name: str):
    """Serves locally-cached merged videos / scene media (dev-storage
    fallback only)."""
    if not _MEDIA_NAME_RE.match(name):
        raise HTTPException(status_code=404, detail="Not found")
    path = _local_media_dir() / name
    if not path.is_file():
        raise HTTPException(status_code=404, detail="Not found")
    ext = name.rsplit(".", 1)[-1].lower()
    return FileResponse(path, media_type=_MEDIA_CONTENT_TYPES.get(ext, "application/octet-stream"))


_SCENE_MEDIA_MAX_BYTES = 30 * 1024 * 1024  # 30 MB — matches /assets/reference's cap.


@router.post("/story/scene-media", dependencies=[require_permission("resources:write")])
async def upload_scene_media(
    file: UploadFile = File(...),
    duration: float = Form(5.0),
    aspect_ratio: str = Form("16:9"),
    resolution: str = Form("1080p"),
    ctx: PluginContext = Depends(get_ctx),
):
    """Turns a directly-uploaded image or video into a ready-to-merge scene —
    Animate's "add a scene" for something the user supplies themselves (e.g.
    a closing "thank you" card) rather than generating through the AI
    pipeline. An image is looped into a short silent(-audio-track) clip of
    `duration` seconds; a video is used as-is, with its real duration
    measured and a poster frame extracted. Both come back normalized to the
    run's aspect ratio/resolution so they concatenate cleanly with every
    other scene regardless of where in the timeline the user places it."""
    data = await file.read()
    if not data:
        raise HTTPException(status_code=400, detail="Empty file")
    if len(data) > _SCENE_MEDIA_MAX_BYTES:
        raise HTTPException(status_code=413, detail="File too large (max 30MB)")

    content_type = (file.content_type or "").lower()
    is_video = content_type.startswith("video/")
    is_image = content_type.startswith("image/")
    if not is_video and not is_image:
        raise HTTPException(status_code=400, detail="Only image or video files are supported")

    ffmpeg = find_ffmpeg()
    if not ffmpeg:
        raise HTTPException(
            status_code=503,
            detail=f"ffmpeg is not available in this environment: {ffmpeg_unavailable_reason()}",
        )

    suffix = (Path(file.filename or "").suffix or (".mp4" if is_video else ".jpg")).lower()
    with tempfile.TemporaryDirectory(prefix="story-scene-media-") as tmp:
        src_path = os.path.join(tmp, f"src{suffix}")
        Path(src_path).write_bytes(data)
        width, height = dimensions_for(aspect_ratio, resolution)

        if is_image:
            clip_duration = max(1.0, min(30.0, duration))
            out_path = os.path.join(tmp, "clip.mp4")
            await anyio.to_thread.run_sync(
                functools.partial(image_to_video, ffmpeg, src_path, out_path, width, height, clip_duration)
            )
            video_url = await _store_media(ctx, Path(out_path).read_bytes(), "video/mp4", "mp4")
            image_url = await _store_media(
                ctx, data, content_type or "image/jpeg", suffix.lstrip(".") or "jpg"
            )
            return {
                "status": "success",
                "image_url": image_url,
                "video_url": video_url,
                "duration": clip_duration,
            }

        # Video upload: measure its real duration on the ORIGINAL file first
        # (re-encoding can shift the container's reported duration slightly),
        # then re-encode to fill the run's WxH exactly — cropping whatever
        # doesn't fit rather than leaving it at its own aspect ratio, same
        # treatment an uploaded image gets in image_to_video above.
        real_duration = (
            await anyio.to_thread.run_sync(functools.partial(probe_duration, ffmpeg, src_path))
        ) or duration
        reencoded_path = os.path.join(tmp, "reencoded.mp4")
        await anyio.to_thread.run_sync(
            functools.partial(reencode_scene_video, ffmpeg, src_path, reencoded_path, width, height)
        )

        image_url: Optional[str] = None
        try:
            thumb_path = os.path.join(tmp, "thumb.jpg")
            await anyio.to_thread.run_sync(
                functools.partial(extract_first_frame, ffmpeg, reencoded_path, thumb_path)
            )
            image_url = await _store_media(ctx, Path(thumb_path).read_bytes(), "image/jpeg", "jpg")
        except Exception as e:  # noqa: BLE001 — cosmetic only, the video itself still ships
            logger.warning("Scene video poster extraction failed: %s", e)

        video_url = await _store_media(ctx, Path(reencoded_path).read_bytes(), "video/mp4", "mp4")
        return {
            "status": "success",
            "image_url": image_url,
            "video_url": video_url,
            "duration": round(real_duration, 2),
        }


_NARRATION_SYSTEM = """You write a short spoken narration script for a video, sized to fit naturally within a given time budget.

Return ONLY a JSON object of this exact shape: {"narration": "..."}

Rules:
- Plain spoken prose — no stage directions, headings, or on-screen text cues.
- Written in the same language the story is described in.
- Must comfortably fit within the given time budget at a natural speaking pace — stay at or under the given word limit.
- Cover the story's actual arc; don't pad, repeat ideas, or trail off just to fill time."""


async def _write_fitted_narration(
    ctx: PluginContext, story: str, target_seconds: float, llm: Optional[str]
) -> str:
    """Auto-narration (no user-authored script) is written HERE, sized to
    the ACTUAL merged video's runtime, rather than just reading the story
    synopsis verbatim regardless of how long the video actually is — which
    can now diverge freely from what was originally planned once scenes are
    added/removed/reordered on Animate, at planning time nobody could size
    a fixed synopsis for. Falls back to the raw synopsis on any failure (no
    LLM configured, bad response, …) — the merge still ships either way."""
    story = (story or "").strip()
    if not story:
        return ""
    buffer_seconds = min(max(target_seconds * 0.08, 1.0), 2.5)
    target = max(3.0, target_seconds - buffer_seconds)
    max_words = max(8, int(target * 2.3))  # ~2.3 words/sec average speaking pace
    user_text = (
        f"Story: {story}\n\n"
        f"Write a natural spoken narration of this story.\n"
        f"Requirements:\n"
        f"- Maximum {max_words} words.\n"
        f"- Must comfortably fit within {target:.1f} seconds of speech.\n"
        f"- Finish naturally before the video ends — do not pad or repeat ideas."
    )
    try:
        data = await _llm_json(ctx, _NARRATION_SYSTEM, user_text, llm)
        narration = str(data.get("narration") or "").strip()
        return narration or story
    except Exception as e:  # noqa: BLE001 — the plain story synopsis still works as narration
        logger.warning("Auto-narration write failed, falling back to the story synopsis: %s", e)
        return story


@router.post("/story/merge", dependencies=[require_permission("resources:write")])
async def run_story_merge(
    request: StoryMergeRequest,
    ctx: PluginContext = Depends(get_ctx),
):
    org_id = ctx.organization_id
    bind_user_id(ctx.user_id)

    urls = [str(u).strip() for u in (request.video_urls or []) if u and str(u).strip()]
    if len(urls) < 2:
        raise HTTPException(status_code=400, detail="At least two scene videos are required")

    ffmpeg = find_ffmpeg()
    if not ffmpeg:
        raise HTTPException(
            status_code=503,
            detail=(
                "ffmpeg is not available in this environment, cannot merge scene "
                f"clips: {ffmpeg_unavailable_reason()}"
            ),
        )

    if request.project_id:
        project = await get_project(ctx.db, ctx.user_id, request.project_id)
        if not project:
            raise HTTPException(status_code=404, detail="Project not found")
        if not request.key_frame_id:
            raise HTTPException(status_code=400, detail="key_frame_id is required")
        kf = await get_key_frame(ctx.db, ctx.user_id, request.project_id, request.key_frame_id)
        if kf is None:
            raise HTTPException(status_code=404, detail="Key frame not found")
        project_id = request.project_id
        key_frame_id = kf["id"]
    else:
        project_id = str(uuid.uuid4())
        key_frame_id = None

    generation_id = str(uuid.uuid4())
    merged_params: dict = {
        "aspect_ratio": request.aspect_ratio or "16:9",
        "resolution": request.resolution or "1080p",
        "source": "story",
        "scene_count": len(urls),
    }
    if request.duration:
        merged_params["duration"] = request.duration.rstrip("sS").strip() or request.duration
    if request.scenes:
        merged_params["scenes"] = request.scenes

    # The bg task mirrors /generate/video's contract: create the item, then
    # started → processing (download/merge logs) → completed/failed over SSE.
    async def _bg():
        async with standalone_background_session(ctx) as db:
            doc = await create_initial_item(
                db,
                organization_id=ctx.organization_id, user_id=ctx.user_id,
                type="video", model_name=LONG_VIDEO_MODEL,
                prompt=request.prompt or "", params=merged_params,
                project_id=project_id, key_frame_id=key_frame_id,
                generation_id=generation_id,
            )
            record_id = doc["id"]
            await broadcast_event(
                org_id, "started",
                {**doc, "project_id": project_id, "generation_id": generation_id},
                record_id, project_id, ctx.user_id,
            )

            async def _progress(message: str):
                await broadcast_event(
                    org_id, "processing",
                    {
                        "id": record_id,
                        "model_name": LONG_VIDEO_MODEL,
                        "project_id": project_id,
                        "generation_id": generation_id,
                        "key_frame_id": key_frame_id,
                        "status": "processing",
                        "prompt": request.prompt,
                        "aspect_ratio": merged_params.get("aspect_ratio"),
                        "duration": merged_params.get("duration"),
                        "logs": [message],
                    },
                    record_id, project_id, ctx.user_id,
                )

            try:
                with tempfile.TemporaryDirectory(prefix="story-merge-") as tmp:
                    paths: list[str] = []
                    async with httpx.AsyncClient(timeout=300, follow_redirects=True) as client:
                        for i, u in enumerate(urls):
                            await _progress(f"Downloading scene {i + 1}/{len(urls)}…")
                            path = os.path.join(tmp, f"clip_{i:03d}.mp4")
                            if u.startswith("file://"):
                                # Local dev storage clip — copy straight from disk.
                                shutil.copyfile(unquote(urlparse(u).path), path)
                            else:
                                resp = await client.get(u)
                                resp.raise_for_status()
                                with open(path, "wb") as f:
                                    f.write(resp.content)
                            paths.append(path)

                    await _progress(f"Merging {len(paths)} scenes with ffmpeg…")
                    width, height = dimensions_for(
                        merged_params.get("aspect_ratio"), merged_params.get("resolution")
                    )
                    out_path = os.path.join(tmp, "merged.mp4")
                    await anyio.to_thread.run_sync(
                        functools.partial(
                            merge_videos, ffmpeg, paths, out_path, width, height
                        )
                    )

                    # Generated-audio modes: the scene clips themselves were
                    # rendered audio-less (see /generate/video's audio flag),
                    # so `out_path` here is a silent concat — layer narration/
                    # music (ElevenLabs) and captions (ffmpeg drawtext) on top.
                    audio_mode = (request.audio_mode or "").strip().lower()
                    # Narration is wanted whenever voiceover_music is picked,
                    # whether the user typed their own script or not — a
                    # blank narration_text auto-writes one from the story
                    # synopsis below, sized to the real merged runtime.
                    wants_narration = audio_mode == "voiceover_music" and bool(
                        (request.narration_text or "").strip() or (request.story or "").strip()
                    )
                    # voiceover_music ALWAYS wants background music (falls
                    # back to a plain ambient prompt below if the user didn't
                    # write one) — a plain "music" pick still needs an
                    # actual prompt, since there narration isn't filling the
                    # silence if the user left this blank too.
                    wants_music = audio_mode == "voiceover_music" or (
                        audio_mode == "music" and bool((request.music_prompt or "").strip())
                    )
                    wants_captions = wants_narration and bool(request.captions_enabled)
                    if wants_narration or wants_music:
                        eleven_key = read_secret(ctx, "ELEVEN_API_KEY")
                        if not eleven_key:
                            await _progress("ELEVEN_API_KEY is not configured — skipping generated audio.")
                        else:
                            # The concat's REAL runtime, not the planned sum
                            # of scene durations — provider clips routinely
                            # land a little short/long of what was
                            # requested, and pinning the audio budget to the
                            # plan instead of reality is exactly what let
                            # narration run past the actual video before (or
                            # end noticeably early).
                            total_seconds = await anyio.to_thread.run_sync(
                                functools.partial(probe_duration, ffmpeg, out_path)
                            )
                            if not total_seconds:
                                total_seconds = float(merged_params.get("duration") or 0) or sum(
                                    float(s.get("duration") or 0) for s in (request.scenes or [])
                                ) or 30.0
                            narration_path: Optional[str] = None
                            music_path: Optional[str] = None
                            captions: Optional[list] = None
                            narration_rate = 1.0

                            # Narration and music are generated by two
                            # separate ElevenLabs APIs (TTS vs. Music) that
                            # can fail independently (access, rate limits,
                            # content policy). Each gets its OWN try/except
                            # so one failing never silently throws away an
                            # already-successful other track — previously
                            # both lived in one shared try block, so a
                            # music-generation error discarded a perfectly
                            # good narration too (and vice versa).
                            if wants_narration:
                                try:
                                    narration_source = (request.narration_text or "").strip()
                                    if not narration_source:
                                        await _progress("Writing narration for this video's length…")
                                        narration_source = await _write_fitted_narration(
                                            ctx, request.story or "", total_seconds, request.llm
                                        )
                                    await _progress("Generating narration…")
                                    voice_id = (
                                        (request.narration_voice_id or "").strip()
                                        or elevenlabs_helper.DEFAULT_VOICE_ID
                                    )
                                    narration_bytes, words = await elevenlabs_helper.generate_narration(
                                        eleven_key,
                                        narration_source,
                                        voice_id,
                                        (request.narration_language or "").strip() or None,
                                    )
                                    narration_path = os.path.join(tmp, "narration.mp3")
                                    Path(narration_path).write_bytes(narration_bytes)
                                    # Narration is free-typed by the user (no
                                    # word-budget applied before TTS), so it
                                    # can easily run longer than the video.
                                    # Reserve a small tail buffer and, if the
                                    # narration overshoots that budget, speed
                                    # it up moderately (capped so it never
                                    # sounds rushed) instead of letting the
                                    # final `-t` trim below chop it off
                                    # mid-sentence.
                                    narration_seconds = (words[-1].get("end") or 0.0) if words else 0.0
                                    buffer_seconds = min(max(total_seconds * 0.08, 0.5), 2.0)
                                    target_seconds = max(1.0, total_seconds - buffer_seconds)
                                    if narration_seconds > target_seconds:
                                        narration_rate = min(1.15, narration_seconds / target_seconds)
                                    if wants_captions:
                                        captions = elevenlabs_helper.group_captions(words)
                                        if narration_rate != 1.0:
                                            captions = [
                                                {
                                                    **c,
                                                    "start": (c["start"] or 0.0) / narration_rate,
                                                    "end": (c["end"] or 0.0) / narration_rate,
                                                }
                                                for c in captions
                                            ]
                                except Exception as narration_err:  # noqa: BLE001 — music/mux still proceed
                                    logger.warning("⚠️ Story narration generation failed: %s", narration_err)
                                    await _progress(
                                        f"Narration generation failed ({narration_err}); continuing without it."
                                    )
                                    narration_path = None
                                    captions = None
                                    narration_rate = 1.0

                            if wants_music:
                                try:
                                    await _progress("Generating music…")
                                    music_source = (request.music_prompt or "").strip()
                                    if not music_source:
                                        # voiceover_music with no music prompt
                                        # typed — still wants background
                                        # music, just with a sensible default
                                        # rather than nothing at all.
                                        music_source = (
                                            "Soft, understated ambient background music for a narrated "
                                            "video — gentle, unobtrusive, no vocals, no lyrics, no sudden "
                                            "dynamic swings that would compete with spoken narration."
                                        )
                                    music_bytes = await elevenlabs_helper.generate_music(
                                        eleven_key, music_source, int(total_seconds * 1000)
                                    )
                                    music_path = os.path.join(tmp, "music.mp3")
                                    Path(music_path).write_bytes(music_bytes)
                                except Exception as music_err:  # noqa: BLE001 — narration/mux still proceed
                                    logger.warning("⚠️ Story music generation failed: %s", music_err)
                                    await _progress(
                                        f"Music generation failed ({music_err}); continuing without it."
                                    )
                                    music_path = None

                            if narration_path or music_path or captions:
                                try:
                                    await _progress("Mixing generated audio into the final video…")
                                    mixed_path = os.path.join(tmp, "mixed.mp4")
                                    await anyio.to_thread.run_sync(
                                        functools.partial(
                                            mux_final_audio, ffmpeg, out_path, mixed_path, total_seconds,
                                            narration_path=narration_path, music_path=music_path,
                                            captions=captions, narration_rate=narration_rate,
                                        )
                                    )
                                    out_path = mixed_path
                                except Exception as mux_err:  # noqa: BLE001 — the plain merged video still ships
                                    logger.warning("⚠️ Story audio mux failed: %s", mux_err)
                                    await _progress(f"Mixing generated audio failed ({mux_err}); continuing without it.")

                    await _progress("Uploading the final video…")
                    # Extracted while `out_path` still exists on disk — avoids
                    # re-downloading the video we just wrote to get a thumbnail.
                    thumb = await generate_video_thumbnail_from_file(ctx, out_path)
                    data = Path(out_path).read_bytes()
                    stored = await _store_merged(ctx, data)

                final = await update_item_success(db, record_id, url=stored)
                if thumb:
                    final = await set_item_fields(db, record_id, {"thumbnail_url": thumb}) or final
                final = await set_item_fields(db, record_id, {"is_favourite": True}) or final
                await broadcast_event(org_id, "completed", final, record_id, project_id, ctx.user_id)
                if request.project_id:
                    await touch_project(db, ctx.user_id, request.project_id)
            except Exception as e:  # noqa: BLE001 — surfaced on the item itself
                logger.exception("❌ Story merge failed")
                failed = await update_item_failed(db, record_id, f"Merge failed: {e}")
                await broadcast_event(org_id, "failed", failed, record_id, project_id, ctx.user_id)

    asyncio.create_task(_bg())

    return {
        "status": "pending",
        "project_id": project_id,
        "generation_id": generation_id,
        "message": "Merge started. Subscribe to /events/{project_id} for SSE updates.",
    }

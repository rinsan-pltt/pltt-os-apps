def _parse_json_block(text: str) -> dict:
    t = (text or "").strip()
    t = re.sub(r"^```(?:json)?\s*|\s*```$", "", t, flags=re.IGNORECASE)
    start, end = t.find("{"), t.rfind("}")
    if start == -1 or end <= start:
        raise ValueError(f"no JSON object in LLM reply: {t[:200]!r}")
    return json.loads(t[start : end + 1])


async def _openai_json(api_key: str, system: str, user: str, model: str = "gpt-5.5") -> dict:
    model = os.getenv("AGENT_OPENAI_MODEL", model)
    async with httpx.AsyncClient(timeout=120) as client:
        r = await client.post(
            "https://api.openai.com/v1/chat/completions",
            headers={"Authorization": f"Bearer {api_key}"},
            json={
                "model": model,
                "response_format": {"type": "json_object"},
                "messages": [
                    {"role": "system", "content": system},
                    {"role": "user", "content": user},
                ],
            },
        )
        r.raise_for_status()
        return _parse_json_block(r.json()["choices"][0]["message"]["content"])


async def _gemini_json(api_key: str, system: str, user: str, model: str = "gemini-3.1-pro") -> dict:
    model = os.getenv("AGENT_GEMINI_MODEL", model)
    async with httpx.AsyncClient(timeout=120) as client:
        r = await client.post(
            f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent",
            headers={"x-goog-api-key": api_key},
            json={
                "system_instruction": {"parts": [{"text": system}]},
                "contents": [{"parts": [{"text": user}]}],
                "generationConfig": {"responseMimeType": "application/json"},
            },
        )
        r.raise_for_status()
        data = r.json()
        return _parse_json_block(data["candidates"][0]["content"]["parts"][0]["text"])



/**
 * App translations, consumed through `useT()` (see ./i18n.ts). The active
 * language follows Palette OS (`usePlatform().language`) — there is no in-app
 * toggle.
 *
 * Conventions:
 * - Supported languages: `en`, `ko`, `ja` (Palette OS `ja-JP` normalizes to
 *   `ja`). `ko` and `ja` must keep identical key sets.
 * - App-chrome strings (buttons, headings, notes) live under `en`, `ko` and
 *   `ja`. A missing `ko`/`ja` key falls back to `en` automatically.
 * - The tool/workflow *registry* data (titles, descriptions, action labels and
 *   every option's label/placeholder/choices) lives under `ko` and `ja` only.
 *   Those call sites pass the existing English string from lib/tools.ts /
 *   lib/workflows.ts as the `defaultValue`, so English needs no duplicate copy
 *   here and a missing `ko`/`ja` entry simply shows the English original.
 *
 * Key scheme for registry data (all segments are dot-safe — slugs, option
 * names and choice values never contain a "."):
 *   tools.<slug>.title | .description | .actionLabel
 *   categories.<Category>
 *   to.<slug>.<optName>              tool option label
 *   tp.<slug>.<optName>              tool option placeholder
 *   tc.<slug>.<optName>.<value>      tool option choice label
 *   wf.<slug>.title | .description   built-in workflow
 *   wfStep.<English step label>      workflow step chip label
 *   wo.<wfSlug>.<stepIndex>.<name>   workflow prompt-option label
 *   wp.<wfSlug>.<stepIndex>.<name>   workflow prompt-option placeholder
 *   langs.<English language name>    translate-workspace language names
 *   ai.fixType.<type>                proofreader fix categories
 */


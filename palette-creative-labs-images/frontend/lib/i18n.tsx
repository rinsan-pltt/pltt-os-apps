const resources: TranslationResources = { en, ko }

/**
 * Translation hook. Returns `t(key, values?, defaultValue?)` plus the active
 * language. Follows the Palette OS language automatically.
 */
export function useT() {
  return usePluginTranslations(resources, { fallbackLanguage: "en" })
}

/**
 * Localized relative-time formatter. Returns a stable callback that renders
 * timestamps like "5m ago" / "5분 전" in the active language.
 */
export function useTimeAgo() {
  const { t } = useT()
  return React.useCallback(
    (dateStr?: string) => {
      if (!dateStr) return ""
      const trimmed = dateStr.replace(/(\.\d{3})\d+/, "$1")
      const normalized = /[Zz]$|[+-]\d{2}:\d{2}$/.test(trimmed) ? trimmed : `${trimmed}Z`
      const diff = Date.now() - new Date(normalized).getTime()
      const secs = Math.floor(diff / 1000)
      if (secs < 60) return t("time.secondsAgo", { n: secs })
      const mins = Math.floor(secs / 60)
      if (mins < 60) return t("time.minutesAgo", { n: mins })
      const hrs = Math.floor(mins / 60)
      if (hrs < 24) return t("time.hoursAgo", { n: hrs })
      return t("time.daysAgo", { n: Math.floor(hrs / 24) })
    },
    [t],
  )
}

